export function translatePresentationMessage(locale: LabLocale, source: string): string {
	if (locale === 'zh-TW') {
		const translated = zhTWPresentationMessages[source]
		if (translated !== undefined)
			return translated
		const trip = translateTripBudgetMessage(locale, source)
		if (trip !== undefined)
			return trip
		const quote = translateQuoteRulesMessage(locale, source)
		if (quote !== undefined)
			return quote
		const onboarding = translateOnboardingMessage(locale, source)
		if (onboarding !== undefined)
			return onboarding
		const repair = translateDocumentRepairMessage(locale, source)
		if (repair !== undefined)
			return repair
		const packs = translateRendererPacksMessage(locale, source)
		if (packs !== undefined)
			return packs
	}
	return translateMessage(locale, source)
}
