import { expect, loadPreset, openEditStructure, openStatusDetails, openTool, test } from './fixtures'

test('Edit exposes the Core catalog (Browse widget types), Structure commands, and synchronized JSON', async ({ page }) => {
	await page.goto('/?showcase=sandbox')

	await page.getByTestId('browse-widget-types')
		.click()
	await expect(page.getByTestId('author-catalog-Stack'))
		.toContainText('Sandbox stack widget')
	await page.keyboard.press('Escape')
	await expect(page.getByTestId('catalog-dialog'))
		.toBeHidden()

	await openEditStructure(page)
	await page.getByRole('button', { name: 'title : Text' })
		.click()
	await page.getByLabel('text', { exact: true })
		.fill('edited in Structure')
	await page.keyboard.press('Enter')

	await openStatusDetails(page)
	await expect(page.getByTestId('status-document-revision'))
		.toHaveText('r1')
	await page.keyboard.press('Escape')
	await expect(page.getByTestId('author-command-outcome'))
		.toContainText('Change applied')

	await page.getByTestId('author-view-json')
		.click()
	await expect(page.locator('.view-lines'))
		.toContainText('edited in Structure')
})

test('recovery keeps unresolved/raw-slot nodes visible and navigates node diagnostics through Document focus', async ({ page }) => {
	await page.goto('/?showcase=sandbox')
	await loadPreset(page, 'raw-slot-recovery')
	await openStatusDetails(page)
	await expect(page.getByTestId('status-recovery'))
		.toContainText('1 unresolved')
	await expect(page.getByTestId('status-recovery'))
		.toContainText('1 raw-slot placements')
	await page.keyboard.press('Escape')
	await openTool(page, 'blueprint')
	// Scoped to the Blueprint tree: the Edit tab beside it lists the same widgets in its Structure tree.
	const blueprint = page.getByRole('tabpanel', { name: 'Blueprint tree' })
	await blueprint.getByRole('button', { name: /All diagnostics/ })
		.click()

	await expect(blueprint.getByRole('button', { name: 'mystery-1 : MysteryWidget' }))
		.toBeVisible()
	await expect(blueprint.getByRole('button', { name: 'orphan-1 : Text' }))
		.toBeVisible()
	await expect(blueprint.getByText('sidebar · raw-slot', { exact: true }))
		.toBeVisible()

	const unresolvedDiagnostic = page.locator('[data-testid^="blueprint-diagnostic-"]')
		.filter({ hasText: 'mystery-1 : MysteryWidget' })
		.first()
	await expect(unresolvedDiagnostic)
		.toBeVisible()
	await expect(unresolvedDiagnostic.getByRole('button', { name: 'jump to node' }))
		.toBeVisible()
	const mysteryNode = blueprint.getByRole('button', { name: 'mystery-1 : MysteryWidget' })
	const orphanNode = blueprint.getByRole('button', { name: 'orphan-1 : Text' })
	const mysteryBackgroundBefore = await mysteryNode.evaluate(element => getComputedStyle(element).backgroundColor)
	await unresolvedDiagnostic.getByRole('button', { name: 'jump to node' })
		.click()
	await expect.poll(() => mysteryNode.evaluate(element => getComputedStyle(element).backgroundColor))
		.not.toBe(mysteryBackgroundBefore)
	const mysteryBackgroundAfter = await mysteryNode.evaluate(element => getComputedStyle(element).backgroundColor)
	// `/rgb/` also matches transparent `rgba(...)`; the selected row must have the actual computed
	// surface color and must differ from the unselected recovered sibling.
	expect(mysteryBackgroundAfter)
		.toMatch(/^rgb\(/)
	expect(await orphanNode.evaluate(element => getComputedStyle(element).backgroundColor))
		.not.toBe(mysteryBackgroundAfter)

	await openStatusDetails(page)
	const recoveryStatus = page.getByTestId('status-recovery')
	await expect(recoveryStatus)
		.toContainText('1 unresolved')
	await expect(recoveryStatus)
		.toContainText('1 raw-slot placements')
})

test('semantic diagnostics navigate to current Document focus while source-only diagnostics remain non-navigable', async ({ page }) => {
	await page.goto('/?showcase=sandbox')
	await loadPreset(page, 'invalid-semantic')
	await openTool(page, 'blueprint')
	// Scoped to the Blueprint tree: the Edit tab beside it lists the same widgets in its Structure tree.
	const blueprint = page.getByRole('tabpanel', { name: 'Blueprint tree' })
	await blueprint.getByRole('button', { name: /All diagnostics/ })
		.click()

	const semanticDiagnostic = page.locator('[data-testid^="blueprint-diagnostic-"]')
		.filter({ hasText: 'summary-1 : Summary' })
		.first()
	await expect(semanticDiagnostic.getByRole('button', { name: 'jump to node' }))
		.toBeVisible()
	const summaryNode = blueprint.getByRole('button', { name: 'summary-1 : Summary' })
	const counterNode = blueprint.getByRole('button', { name: 'counter-1 : Counter' })
	const summaryBackgroundBefore = await summaryNode.evaluate(element => getComputedStyle(element).backgroundColor)
	await semanticDiagnostic.getByRole('button', { name: 'jump to node' })
		.click()
	await expect.poll(() => summaryNode.evaluate(element => getComputedStyle(element).backgroundColor))
		.not.toBe(summaryBackgroundBefore)
	const summaryBackgroundAfter = await summaryNode.evaluate(element => getComputedStyle(element).backgroundColor)
	// The diagnostic navigation must move the actual Document focus, not merely render a diagnostic
	// whose own transparent background happens to contain the substring "rgb".
	expect(summaryBackgroundAfter)
		.toMatch(/^rgb\(/)
	expect(await counterNode.evaluate(element => getComputedStyle(element).backgroundColor))
		.not.toBe(summaryBackgroundAfter)

	await page.goto('/?lab-test&lang=en')
	await page.waitForFunction(() => typeof (window as any).__WIDGET_LAB_TEST__?.editJson === 'function')
	await page.evaluate(() => (window as any).__WIDGET_LAB_TEST__.editJson('{'))
	await openStatusDetails(page)
	await expect(page.getByTestId('status-json-draft'))
		.toContainText('Syntax error, not applied (Lab-only)')
	await expect(page.getByTestId('status-source-compat'))
		.toContainText('Compatible (Core)')
	await expect(page.getByTestId('status-blueprint'))
		.toContainText('valid')
})

test('rejects blank numeric Structure values while preserving scalar editing behavior', async ({ page }) => {
	await page.goto('/')
	await openEditStructure(page)
	await page.getByRole('button', { name: 'guests : Numeric' })
		.click()

	const maxField = page.getByLabel('max', { exact: true })
	await maxField.fill('   ')
	// Leaving the box commits it (Lab UX phase 3); what is not a number is refused there too.
	await maxField.blur()
	// The refusal is shown at the field, and nothing was sent to the Document.
	await expect(page.locator('[data-config-path="max"]')
		.getByRole('alert'))
		.toHaveText('Enter a number, such as 12 or 2.5.')
	await expect(page.getByTestId('author-command-outcome'))
		.toHaveCount(0)

	await maxField.fill('2')
	await maxField.press('Enter')
	await expect(page.getByTestId('author-command-outcome'))
		.toContainText('Change applied')
})
